def crop_render(pic, margin=22):
    img=Image.open(pic).convert('RGB')
    a=np.asarray(img)
    # VTK fixed RGB background approximately (244,242,236); detect scene colour distance
    bg=a[2,2].astype(int)
    delta=np.max(np.abs(a.astype(int)-bg),axis=2)
    yy,xx=np.nonzero(delta>25)
    if len(xx)==0:return img
    x0=max(0,int(xx.min())-margin);x1=min(img.width,int(xx.max())+margin)
    y0=max(0,int(yy.min())-margin);y1=min(img.height,int(yy.max())+margin)
    return img.crop((x0,y0,x1,y1))

