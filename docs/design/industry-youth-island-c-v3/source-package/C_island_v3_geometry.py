def colorhex(x): return tuple(int(C.get(x,x).lstrip('#')[i:i+2],16) for i in (0,2,4))
def add(n,m,c):
 if not isinstance(m,trimesh.Trimesh): return
 m=m.copy();m.visual.face_colors=np.array((*colorhex(c),255),dtype=np.uint8)
 M.append((n,m,c));return m

def box(n,loc,scale,c):
 m=trimesh.creation.box(extents=scale);m.apply_translation(loc);return add(n,m,c)

def cylinder(n,loc,radius,height,c,sections=20):
 m=trimesh.creation.cylinder(radius=radius,height=height,sections=sections)
 m.apply_translation(loc);return add(n,m,c)

def sphere(n,loc,radius,c,sub=1,scale=None):
 m=trimesh.creation.icosphere(subdivisions=sub,radius=radius)
 if scale is not None:m.apply_scale(scale)
 m.apply_translation(loc);return add(n,m,c)

def polygon_prism(n,poly,z0,z1,c):
 poly=Polygon(poly)
 if not poly.is_valid:poly=poly.buffer(0)
 if poly.is_empty:return
 xy=np.array(poly.exterior.coords[:-1])
 verts=[[x,y,z0] for x,y in xy]+[[x,y,z1] for x,y in xy]
 N=len(xy);faces=[]
 for i in range(N):
  j=(i+1)%N;faces.extend([[i,j,j+N],[i,j+N,i+N]])
 # top triangulation and map coordinates
 for tri in triangulate(poly):
  p=tri.representative_point()
  if not poly.covers(p):continue
  ids=[]
  for pxy in tri.exterior.coords[:3]:
   ids.append(len(verts));verts.append([*pxy,z1])
  faces.append(ids)
 m=trimesh.Trimesh(vertices=np.array(verts),faces=np.array(faces),process=False)
 return add(n,m,c)

def beam(n,a,b,r,c,sections=8):
 a=np.array(a);b=np.array(b);d=b-a
 if np.linalg.norm(d)<1e-5:return
 m=trimesh.creation.cylinder(radius=r,height=np.linalg.norm(d),sections=sections)
 T=trimesh.geometry.align_vectors([0,0,1],d);m.apply_transform(T);m.apply_translation((a+b)/2)
 add(n,m,c)

def roof_strip(n,verts,c):
 # thin planar quad mesh with tops, simply sufficient to convey buildable roof plate
 p=np.array(verts,float)
 m=trimesh.Trimesh(vertices=p,faces=[[0,1,2],[0,2,3]],process=False)
 add(n,m,c)

